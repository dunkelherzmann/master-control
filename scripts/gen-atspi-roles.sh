#!/bin/sh
# Writes agent/src/desktop/atspi_roles.rs from the libatspi of the Linux machine, reached through Master Control
# (mc-exec) as linux, or as MC_LINUX_HOST from the environment or scripts/hosts.env, so the role names and numbers
# come from AT-SPI's own list and not from memory. Toolkits that answer GetRole but not GetRoleName (AccessKit, which
# egui and other Rust toolkits use) need it. Run it again for newer AT-SPI releases.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PATH="$ROOT/scripts:$PATH"  # mc-exec: the copy in this repository, so nothing beyond mctl is needed
OUT="$ROOT/agent/src/desktop/atspi_roles.rs"
[ -f "$ROOT/scripts/hosts.env" ] && . "$ROOT/scripts/hosts.env"
LINUX_HOST="${MC_LINUX_HOST:-linux}"
{
    echo "//! AT-SPI's role names by number. Generated by scripts/gen-atspi-roles.sh from libatspi"
    echo "//! ($(mc-exec "$LINUX_HOST" "dpkg-query -W -f='\${Package} \${Version}' libatspi2.0-0t64")); don't edit by hand."
    echo
    echo "pub const NAMES: &[&str] = &["
    mc-exec "$LINUX_HOST" "python3 -c \"
import gi
gi.require_version('Atspi', '2.0')
from gi.repository import Atspi
for number in range(int(Atspi.Role.LAST_DEFINED)):
    print('    \\\"%s\\\",' % Atspi.role_get_name(Atspi.Role(number)))
\""
    echo "];"
} >"$OUT"
echo "wrote $OUT: $(grep -c '^    "' "$OUT") roles"
