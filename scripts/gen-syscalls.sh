#!/bin/sh
# Writes agent/src/observe/syscalls_x86_64.rs from the kernel headers of the Linux machine (MC_LINUX_HOST, or the
# one named in scripts/hosts.env), so the
# names and numbers come from the kernel's own list and not from memory. Run it again for newer kernels.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/agent/src/observe/syscalls_x86_64.rs"
[ -f "$ROOT/scripts/hosts.env" ] && . "$ROOT/scripts/hosts.env"
LINUX_HOST="${MC_LINUX_HOST:-linux}"
HEADER=/usr/include/x86_64-linux-gnu/asm/unistd_64.h
{
    echo "//! System call names by number on x86-64. Generated by scripts/gen-syscalls.sh from the kernel's"
    echo "//! asm/unistd_64.h ($(ssh "$LINUX_HOST" "dpkg-query -W -f='\${Package} \${Version}' linux-libc-dev")); don't edit by hand."
    echo
    echo "pub const NAMES: &[(u32, &str)] = &["
    ssh "$LINUX_HOST" "awk '/^#define __NR_/ { sub(/^__NR_/, \"\", \$2); printf \"    (%s, \\\"%s\\\"),\\n\", \$3, \$2 }' $HEADER"
    echo "];"
} >"$OUT"
echo "wrote $OUT: $(grep -c '^    (' "$OUT") system calls"
